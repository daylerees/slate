"""Shared pieces of Slate's app theming (used by apply-theme.py and slate_apps.py):
colours, careful file editing, and an undo log so any app's theming can be switched off
again, putting its config back the way it was.

Every change Slate makes to an app's config is recorded in
~/.local/state/slate/app-theming.json, per app:
  file      a file Slate generated (a theme file): deleted on undo
  created   a starting config Slate made because there was none: deleted on undo if it's
            still exactly what Slate wrote (once Slate's own lines are taken out)
  line      a line Slate added to your config: removed on undo
  replace   a line of yours Slate replaced: put back on undo (if Slate's line is still there)
  block     a block of lines Slate added: removed on undo
  ini       an INI/TOML key Slate set: your old value (or none) put back
  jsonc     a top-level key in a JSON-with-comments settings file: old value put back
  jsonlist  an item Slate added to a JSON list: removed
  gsettings a GSettings key: your old value put back
  command   a command that sets something, with the command that sets it back
Config files are also backed up once (<file>.bak-slate-theme) before Slate first edits them.
"""
import colorsys
import json
import os
import re
import shutil
import subprocess

HOME = os.path.expanduser("~")
CFG = os.environ.get("XDG_CONFIG_HOME") or os.path.join(HOME, ".config")
DATA = os.environ.get("XDG_DATA_HOME") or os.path.join(HOME, ".local", "share")
STATE = os.environ.get("XDG_STATE_HOME") or os.path.join(HOME, ".local", "state")
SHELL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(STATE, "slate", "app-theming.json")
GEN = "Generated by Slate (Settings → Appearance → App Theming); changes are overwritten"
changed = []          # files written this run
OWN = set()           # files Slate created itself (not backed up: there's nothing of yours in them)


# ---- Colours ---------------------------------------------------------------------------
def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def hexc(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)

def mix(a, b, t):
    """a blended toward b by t (0..1)"""
    a, b = rgb(a), rgb(b)
    return hexc(tuple(a[i] + (b[i] - a[i]) * t for i in range(3)))

def luminance(h):
    v = [x / 255 for x in rgb(h)]
    v = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in v]
    return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]

def contrast(a, b):
    x, y = sorted((luminance(a), luminance(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)

def readable(h, bg, ratio=4.5):
    """h, darkened (on a light bg) or lightened (on a dark bg) just enough to reach ratio"""
    if contrast(h, bg) >= ratio:
        return h
    toward = "#000000" if luminance(bg) > 0.18 else "#ffffff"
    lo, hi = 0.0, 1.0
    for _ in range(20):
        mid = (lo + hi) / 2
        if contrast(mix(h, toward, mid), bg) >= ratio:
            hi = mid
        else:
            lo = mid
    return mix(h, toward, hi)

def ink(h):
    """A pastel turned into a clear, saturated colour for light backgrounds (same hue)"""
    r, g, b = (x / 255 for x in rgb(h))
    hue, _, sat = colorsys.rgb_to_hls(r, g, b)
    return hexc(tuple(x * 255 for x in colorsys.hls_to_rgb(hue, 0.36, max(sat, 0.6))))

def bare(h):
    return h.lstrip("#")

def palette(p):
    light = bool(p.get("light"))
    c = dict(p)
    bg, surf, text, dim, acc = p["bg"], p["surface"], p["text"], p["dim"], p["accent"]
    c["light"] = light
    c["onVariant"] = mix(text, dim, 0.4)              # secondary text
    c["secondary"] = mix(acc, dim, 0.45)              # links, mid gradient stops
    # Colours that aren't part of Slate's palette: saturated inks in light mode, and always
    # readable as text on the background (WCAG 4.5:1)
    deep = (lambda h: readable(ink(h), bg)) if light else (lambda h: readable(h, bg))
    c["tertiary"] = deep("#7fc4c0")                  # positive / neutral / warning
    c["green"], c["yellow"], c["magenta"] = deep("#a6d3a0"), deep("#e6cf8e"), deep("#c3a6e6")
    c["orange"] = deep("#e8b48f")
    c["red"] = readable(p["error"], bg)
    c["between"] = mix(bg, surf, 0.5)                 # alternate rows
    c["selection"] = mix(surf, acc, 0.22)             # Qt highlight, KDE window alt
    c["selectedBg"] = mix(surf, acc, 0.1)
    c["box"] = mix(bg, dim, 0.6)
    c["divider"] = mix(bg, dim, 0.45)
    c["shadow"] = mix(bg, "#000000", 0.5) if not light else mix(dim, "#000000", 0.5)
    c["disabled"] = mix(bg, surf, 0.15)
    c["onNegative"] = mix(surf, p["error"], 0.25)
    c["onPositive"] = mix(surf, c["tertiary"], 0.25)
    c["currentLine"] = mix(bg, surf, 0.55)
    # Terminal ANSI colours
    # Programs print "white" as ordinary text, so on a light background it has to be a grey
    # that still reads (as in GitHub Light, Tokyo Night Day), not a near-background tint
    if light:
        c["black"], c["brightBlack"] = mix(text, bg, 0.1), readable(dim, bg, 3.5)
        c["white"] = readable(mix(text, bg, 0.45), bg, 4.5)
        c["brightWhite"] = readable(mix(text, bg, 0.6), bg, 3.0)
        bright = lambda h: readable(mix(h, "#000000", 0.2), bg)
    else:
        c["black"], c["brightBlack"] = mix(bg, surf, 0.78), readable(mix(bg, dim, 0.6), bg, 3.0)
        c["white"] = c["brightWhite"] = text
        bright = lambda h: readable(mix(h, "#ffffff", 0.22), bg)
    c["blue"] = readable(acc, bg)
    c["ansi"] = [c["black"], c["red"], c["green"], c["yellow"], c["blue"], c["magenta"], c["tertiary"], c["white"]]
    c["ansiBright"] = [c["brightBlack"]] + [bright(h) for h in c["ansi"][1:7]] + [c["brightWhite"]]
    # Code: the same roles in every editor
    c["syn"] = {"comment": readable(dim, bg, 3.5), "keyword": c["blue"], "string": c["green"], "number": c["magenta"],
                "constant": c["magenta"], "function": c["tertiary"], "type": c["yellow"],
                "variable": text, "property": mix(text, acc, 0.35), "operator": c["onVariant"],
                "punctuation": c["onVariant"], "tag": c["blue"], "attribute": c["yellow"],
                "heading": c["blue"], "link": c["blue"], "escape": c["orange"], "error": c["red"]}
    return c


# ---- Files ---------------------------------------------------------------------------------
def read(path):
    try:
        with open(path) as f:
            return f.read()
    except (FileNotFoundError, IsADirectoryError, UnicodeDecodeError):
        return None

def write(path, text):
    """Atomic write, only when the contents differ"""
    if read(path) == text:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = os.path.join(os.path.dirname(path), "." + os.path.basename(path) + ".slate-tmp")
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)
    changed.append(path)
    return True

def edit(path, fn):
    """Change a config file in place (backing it up once first); fn(text) -> text"""
    old = read(path) or ""
    new = fn(old)
    if new == old:
        return False
    bak = path + ".bak-slate-theme"
    if old and path not in OWN and not os.path.exists(bak):
        shutil.copy2(path, bak)
    return write(path, new)

def first_existing(*paths):
    return next((p for p in paths if os.path.exists(p)), None)

def have(cmd):
    return shutil.which(cmd) is not None


# ---- INI (and simple TOML sections) --------------------------------------------------------
def _section_bounds(lines, section):
    if section is None:          # keys before the first [section]
        end = next((i for i, l in enumerate(lines) if l.lstrip().startswith("[")), len(lines))
        return -1, end
    start = next((i for i, l in enumerate(lines) if l.strip() == "[%s]" % section), None)
    if start is None:
        return None, None
    end = next((i for i in range(start + 1, len(lines)) if lines[i].lstrip().startswith("[")), len(lines))
    return start, end

def _key_re(key):
    return re.compile(r"\s*%s\s*=" % re.escape(key))

def ini_get(text, section, key):
    lines = text.splitlines()
    start, end = _section_bounds(lines, section)
    if start is None:
        return None
    for i in range(start + 1, end):
        if _key_re(key).match(lines[i]):
            return lines[i].split("=", 1)[1].strip()
    return None

def set_ini_key(text, section, key, value, sep="="):
    """Set key=value inside [section] of an INI-style file, adding either if missing"""
    lines = text.splitlines()
    start, end = _section_bounds(lines, section)
    if start is None:
        if lines and lines[-1].strip():
            lines.append("")
        lines += ["[%s]" % section, "%s%s%s" % (key, sep, value)]
        return "\n".join(lines) + "\n"
    for i in range(start + 1, end):
        if _key_re(key).match(lines[i]):
            lines[i] = "%s%s%s" % (key, sep, value)
            return "\n".join(lines) + "\n"
    while end > start + 1 and not lines[end - 1].strip():
        end -= 1
    lines.insert(end, "%s%s%s" % (key, sep, value))
    return "\n".join(lines) + "\n"

def del_ini_key(text, section, key):
    lines = text.splitlines()
    start, end = _section_bounds(lines, section)
    if start is None:
        return text
    for i in range(start + 1, end):
        if _key_re(key).match(lines[i]):
            del lines[i]
            # drop a section Slate left empty
            if section is not None:
                s2, e2 = _section_bounds(lines, section)
                if s2 is not None and all(not l.strip() for l in lines[s2 + 1:e2]):
                    del lines[s2:e2]
                    # and the blank line set_ini_key put before it, when nothing follows now
                    if s2 > 0 and not lines[s2 - 1].strip() and (s2 == len(lines) or not lines[s2].strip()):
                        del lines[s2 - 1]
            return "\n".join(lines) + ("\n" if lines else "")
    return text


# ---- JSON with comments (VS Code, Zed settings): top-level keys, edited as text ---------
def _skip_ws(t, i):
    while i < len(t):
        if t[i] in " \t\r\n,":
            i += 1
        elif t.startswith("//", i):
            j = t.find("\n", i); i = len(t) if j < 0 else j + 1
        elif t.startswith("/*", i):
            j = t.find("*/", i + 2); i = len(t) if j < 0 else j + 2
        else:
            break
    return i

def _value_end(t, i):
    """End index of the JSON value starting at i"""
    if t[i] == '"':
        j = i + 1
        while j < len(t) and t[j] != '"':
            j += 2 if t[j] == "\\" else 1
        return j + 1
    if t[i] in "{[":
        depth, j = 0, i
        while j < len(t):
            ch = t[j]
            if ch == '"':
                j = _value_end(t, j); continue
            if t.startswith("//", j):
                k = t.find("\n", j); j = len(t) if k < 0 else k; continue
            if t.startswith("/*", j):
                k = t.find("*/", j + 2); j = len(t) if k < 0 else k + 2; continue
            if ch in "{[":
                depth += 1
            elif ch in "}]":
                depth -= 1
                if depth == 0:
                    return j + 1
            j += 1
        return len(t)
    m = re.compile(r"[^,}\]\s]+").match(t, i)
    return m.end() if m else i

def jsonc_find(t, key):
    """(start, end) of the value of a top-level key, or None"""
    i = _skip_ws(t, 0)
    if i >= len(t) or t[i] != "{":
        return None
    i += 1
    while True:
        i = _skip_ws(t, i)
        if i >= len(t) or t[i] == "}":
            return None
        if t[i] != '"':
            return None
        kend = _value_end(t, i)
        name = t[i + 1:kend - 1]
        i = _skip_ws(t, kend)
        if i >= len(t) or t[i] != ":":
            return None
        i = _skip_ws(t, i + 1)
        vend = _value_end(t, i)
        if name == key:
            return i, vend
        i = vend

def jsonc_set(t, key, raw):
    """Set a top-level key to raw JSON text; returns (new text, old raw or None)"""
    if not t.strip():
        return "{\n    %s: %s\n}\n" % (json.dumps(key), raw), None
    span = jsonc_find(t, key)
    if span:
        old = t[span[0]:span[1]]
        return t[:span[0]] + raw + t[span[1]:], old
    i = t.index("{") + 1
    rest = t[i:]
    sep = "," if rest.strip() and not rest.strip().startswith("}") else ""
    return t[:i] + "\n    %s: %s%s" % (json.dumps(key), raw, sep) + rest, None

def jsonc_remove(t, key):
    span = jsonc_find(t, key)
    if not span:
        return t
    # from the key's opening quote to just after the value (and a trailing comma)
    kstart = t.rfind(json.dumps(key), 0, span[0])
    end = span[1]
    m = re.compile(r"\s*,").match(t, end)
    if m:
        end = m.end()
    else:                          # last key: drop the comma before it instead
        before = t[:kstart].rstrip()
        if before.endswith(","):
            kstart = len(before) - 1
    # take the line's leading whitespace too
    ls = t.rfind("\n", 0, kstart)
    if t[ls + 1:kstart].strip() == "":
        kstart = ls if ls >= 0 else kstart
    return t[:kstart] + t[end:]


# ---- Undo log ------------------------------------------------------------------------------
class Ctx:
    """Applies (and records) one app's changes; undo() reverses them"""

    def __init__(self, c, live):
        self.c = c
        self.live = live
        try:
            with open(MANIFEST) as f:
                self.manifest = json.load(f)
        except (FileNotFoundError, ValueError):
            self.manifest = {}
        self.app = None
        for ops in self.manifest.values():
            OWN.update(o["path"] for o in ops if o.get("path") and (o.get("new") or o["t"] in ("created", "file")))

    def save(self):
        os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
        tmp = MANIFEST + ".tmp"
        with open(tmp, "w") as f:
            json.dump(self.manifest, f, indent=1)
        os.replace(tmp, MANIFEST)

    def _ops(self):
        return self.manifest.setdefault(self.app, [])

    def _has(self, op, *keys):
        return next((o for o in self._ops() if o["t"] == op and all(o.get(k) == v for k, v in keys)), None)

    def _record(self, op):
        """Note a change, before it's made: a file (and folders) that don't exist yet are
        Slate's, and are removed again on undo once they're empty"""
        path = op.get("path")
        if path and not os.path.exists(path):
            op["new"] = True
            OWN.add(path)
            dirs, d = [], os.path.dirname(path)
            while d and d != os.path.dirname(d) and not os.path.exists(d):
                dirs.append(d)
                d = os.path.dirname(d)
            op["dirs"] = dirs
        self._ops().append(op)

    # -- making changes --
    def file(self, path, text, empty_on_undo=False):
        """A file Slate owns (a theme): written each time, deleted on undo (or emptied, for
        files something else points at)"""
        if not self._has("file", ("path", path)):
            self._record({"t": "file", "path": path, "empty": empty_on_undo})
        return write(path, text)

    def start(self, path, text):
        """A starting config, only when there's none"""
        if os.path.exists(path):
            return False
        self._record({"t": "created", "path": path, "text": text})
        OWN.add(path)
        return write(path, text)

    def line(self, path, line, top=False, present=None):
        """Make sure a line is in a config file (added at the end, or the top).
        present: a regex; if a line matches it, nothing is added"""
        def fn(t):
            lines = t.splitlines()
            if any(l.strip() == line.strip() for l in lines):
                return t
            if present and re.search(present, t, flags=re.M):
                return t
            if top:
                return line + "\n" + t
            return t.rstrip("\n") + ("\n" if t.strip() else "") + line + "\n"
        cur = read(path) or ""
        if fn(cur) == cur:
            return False
        if not self._has("line", ("path", path), ("line", line)):
            # (whether the file ended in a newline, so taking the line out puts it back as it was)
            self._record({"t": "line", "path": path, "line": line, "eof_nl": cur == "" or cur.endswith("\n")})
        return edit(path, fn)

    def replace(self, path, pattern, new):
        """Replace the line matching pattern (first one) with new, or add new at the end"""
        t = read(path) or ""
        m = re.search(pattern, t, flags=re.M)
        if m:
            old = m.group(0)
            if old == new:
                return False
            if not self._has("replace", ("path", path), ("new", new)):
                self._record({"t": "replace", "path": path, "old": old, "new": new})
            return edit(path, lambda x: x[:m.start()] + new + x[m.end():])
        return self.line(path, new)

    def block(self, path, text, top=False):
        """Add a block of lines (once)"""
        t = read(path) or ""
        if text in t:
            return False
        if not self._has("block", ("path", path), ("text", text)):
            self._record({"t": "block", "path": path, "text": text})
        return edit(path, lambda x: (text + x) if top else (x.rstrip("\n") + ("\n\n" if x.strip() else "") + text))

    def ini(self, path, section, key, value, sep="="):
        t = read(path) or ""
        if not self._has("ini", ("path", path), ("section", section), ("key", key)):
            self._record({"t": "ini", "path": path, "section": section, "key": key,
                          "old": ini_get(t, section, key), "sep": sep})
        return edit(path, lambda x: set_ini_key(x, section, key, value, sep))

    def ini_many(self, path, items, sep="="):
        """Several ini() changes to one file, written once: items = [(section, key, value)]"""
        t = read(path) or ""
        for section, key, _ in items:
            if not self._has("ini", ("path", path), ("section", section), ("key", key)):
                self._record({"t": "ini", "path": path, "section": section, "key": key,
                              "old": ini_get(t, section, key), "sep": sep})
        def fn(x):
            for section, key, value in items:
                x = set_ini_key(x, section, key, value, sep)
            return x
        return edit(path, fn)

    def jsonc(self, path, key, value):
        raw = json.dumps(value)
        t = read(path) or ""
        new, old = jsonc_set(t, key, raw)
        if new == t:
            return False
        if not self._has("jsonc", ("path", path), ("key", key)):
            self._record({"t": "jsonc", "path": path, "key": key, "old": old})
        return edit(path, lambda x: jsonc_set(x, key, raw)[0])

    def jsonlist(self, path, keys, item, match=None):
        """Add item to the list at keys (a path into a plain JSON file; [] = the file is the list)"""
        try:
            data = json.loads(read(path) or ("[]" if not keys else "{}"))
        except ValueError:
            return False
        if keys:
            node = data
            for k in keys[:-1]:
                node = node.setdefault(k, {})
            lst = node.setdefault(keys[-1], [])
        else:
            lst = data
        same = match or (lambda x: x == item)
        if any(same(x) for x in lst):
            return False
        lst.append(item)
        if not self._has("jsonlist", ("path", path), ("keys", keys)):
            self._record({"t": "jsonlist", "path": path, "keys": keys, "item": item, "orig": read(path)})
        return edit(path, lambda _: json.dumps(data, indent=4) + "\n")

    def gsetting(self, schema, key, value, only_if=None):
        """Set a GSettings key (live sessions only); only_if: old values we may replace"""
        if not self.live:
            return False
        cur = run_out(["gsettings", "get", schema, key])
        if cur is None:
            return False
        val = cur.strip()
        if only_if is not None and val.strip("'") not in only_if:
            return False
        if val.strip("'") == value:
            return False
        if not self._has("gsettings", ("schema", schema), ("key", key)):
            self._record({"t": "gsettings", "schema": schema, "key": key, "old": val.strip("'")})
        run(["gsettings", "set", schema, key, value])
        return True

    def command(self, do, undo):
        """Run a command now, and remember the one that reverses it"""
        if not self.live:
            return False
        if not self._has("command", ("undo", undo)):
            self._record({"t": "command", "undo": undo})
        run(do, timeout=60)
        return True

    # -- reversing --
    def undo(self, app):
        ops = self.manifest.pop(app, [])
        for o in reversed(ops):
            try:
                _undo_one(o, self.live)
            except (OSError, ValueError, KeyError):
                pass
        return bool(ops)


def _undo_one(o, live):
    _undo_change(o, live)
    path = o.get("path")
    if path and o.get("new"):
        x = read(path)
        if x is not None and not x.strip():
            os.remove(path)
    for d in o.get("dirs", []):            # deepest first
        try:
            os.rmdir(d)
        except OSError:
            pass

def _undo_change(o, live):
    t, path = o["t"], o.get("path")
    if t == "file":
        if path and os.path.isfile(path):
            if o.get("empty"):
                write(path, "")
            else:
                os.remove(path)
                changed.append(path)
    elif t == "created":
        x = read(path)
        if x is not None and x.strip() == o["text"].strip():
            os.remove(path)
            changed.append(path)
        elif x is not None:
            # You've edited it, so it stays; just take out the lines that point at Slate's
            # theme files (which are gone now)
            ours = [l for l in o["text"].splitlines()
                    if "slate" in l.lower() and not l.lstrip().startswith(("#", "--", "//", ";", '"'))]
            keep = [l for l in x.splitlines() if l not in ours]
            write(path, "\n".join(keep) + "\n")
    elif t == "line":
        def fn(x):
            lines = x.splitlines()
            last = False
            for i, l in enumerate(lines):
                if l.strip() == o["line"].strip():
                    last = i == len(lines) - 1
                    del lines[i]
                    break
            # Slate's line was last: the file ends as it did before (with or without a newline)
            nl = o.get("eof_nl", True) if last else x.endswith("\n")
            return "\n".join(lines) + ("\n" if lines and nl else "")
        if read(path) is not None:
            write(path, fn(read(path)))
    elif t == "replace":
        x = read(path)
        if x is not None and o["new"] in x:
            write(path, x.replace(o["new"], o["old"], 1))
    elif t == "block":
        x = read(path)
        if x is not None and o["text"] in x:
            rest = x.replace(o["text"], "", 1)
            write(path, rest.rstrip("\n") + "\n" if rest.strip() else "")
    elif t == "ini":
        x = read(path)
        if x is not None:
            if o["old"] is None:
                write(path, del_ini_key(x, o["section"], o["key"]))
            else:
                write(path, set_ini_key(x, o["section"], o["key"], o["old"], o.get("sep", "=")))
    elif t == "jsonc":
        x = read(path)
        if x is not None:
            write(path, jsonc_remove(x, o["key"]) if o["old"] is None else jsonc_set(x, o["key"], o["old"])[0])
    elif t == "jsonlist":
        x = read(path)
        if x is not None:
            data = json.loads(x)
            if o["keys"]:
                node = data
                for k in o["keys"][:-1]:
                    node = node.get(k, {})
                lst = node.get(o["keys"][-1], [])
            else:
                lst = data
            if o["item"] in lst:
                lst.remove(o["item"])
                orig = o.get("orig")
                try:
                    same = orig is not None and json.loads(orig) == data
                except ValueError:
                    same = False
                write(path, orig if same else json.dumps(data, indent=4) + "\n")
    elif t == "gsettings":
        if live:
            run(["gsettings", "set", o["schema"], o["key"], o["old"]])
    elif t == "command":
        if live:
            run(o["undo"], timeout=60)


# ---- Running things ------------------------------------------------------------------------
def run(cmd, timeout=5):
    try:
        subprocess.run(cmd, capture_output=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        pass

def run_out(cmd):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=5)
        return r.stdout if r.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None

def signal_all(name, sig):
    """Send a signal to this user's processes with this exact name"""
    run(["pkill", "-" + sig, "-x", "-u", str(os.getuid()), name])

def touched(*parts):
    """Did this run change a file under a folder with these path parts?"""
    return any(os.sep + os.path.join(*parts) in path for path in changed)
